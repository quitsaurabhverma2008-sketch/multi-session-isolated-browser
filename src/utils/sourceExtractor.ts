export async function downloadProjectZip(project: WebWorkframeProject, customName?: string): Promise<void> {
  const zip = new JSZip();

  zip.file('index.html', project.html);
  zip.file('styles.css', project.css);
  zip.file('app.js', project.js);
  zip.file('server.py', project.pythonServer);
  zip.file('requirements.txt', project.requirements);
  zip.file('Dockerfile', project.dockerfile);
  zip.file('README.md', project.readme);

  const content = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 }
  });

  const cleanDomain = (project.stats.domain || 'website').replace(/[^a-zA-Z0-9_-]/g, '_');
  const filename = `${customName || cleanDomain}_full_source_workframe.zip`;

  const link = document.createElement('a');
  link.href = URL.createObjectURL(content);
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(link.href);
}
