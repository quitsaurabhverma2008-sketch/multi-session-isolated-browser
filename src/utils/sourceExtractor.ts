import JSZip from 'jszip';
import { formatHtml } from './htmlFormatter';

export interface WebWorkframeProject {
  html: string;
  css: string;
  js: string;
  pythonServer: string;
  requirements: string;
  dockerfile: string;
  readme: string;
  stats: PageAnalysis;
}

export interface PageAnalysis {
  url: string;
  domain: string;
  title: string;
  totalNodes: number;
  formCount: number;
  inputCount: number;
  buttonCount: number;
  scriptCount: number;
  styleCount: number;
  imageCount: number;
  linkCount: number;
  detectedForms: Array<{
    action: string;
    method: string;
    fields: string[];
    buttonText: string;
  }>;
}

/**
 * Extracts and cleans the web source code, separation of concerns (HTML, CSS, JS),
 * and generates a complete Python Flask backend workframe ready to run locally or deploy.
 */
export function extractWebWorkframe(rawHtml: string, currentUrl: string, pageTitle: string): WebWorkframeProject {
  const urlObj = (() => {
    try {
      if (currentUrl.startsWith('http://') || currentUrl.startsWith('https://')) {
        return new URL(currentUrl);
      }
      return new URL('https://example.com');
    } catch {
      return new URL('https://example.com');
    }
  })();

  const domain = urlObj.hostname || 'website';
  const parser = new DOMParser();
  const doc = parser.parseFromString(rawHtml || '<!DOCTYPE html><html><head><title>Website</title></head><body></body></html>', 'text/html');

  // 1. Remove proxy and bridge injection artifacts
  const bridgeScript = doc.getElementById('__isolated_browser_bridge__');
  if (bridgeScript) bridgeScript.remove();

  const injectedElements = doc.querySelectorAll('[data-xbrowse-injected], #browser-chrome-bar, .xbrowse-internal');
  injectedElements.forEach(el => el.remove());

  // Also remove any existing base tags pointing to proxy
  const baseTags = doc.querySelectorAll('base');
  baseTags.forEach(b => {
    const href = b.getAttribute('href') || '';
    if (href.includes('/api/proxy') || href.includes('localhost')) {
      b.remove();
    }
  });

  // 2. Extract CSS styles
  const styleElements = Array.from(doc.querySelectorAll('style'));
  let aggregatedCss = `/* =========================================================================
   STYLE WORKFRAME - Extracted from ${currentUrl || 'xbrowse'}
   Page: ${pageTitle || 'Web Application'}
   Generated by xbrowse Web Framework Studio
   ========================================================================= */\n\n`;

  aggregatedCss += `*, *::before, *::after {\n  box-sizing: border-box;\n}\n\n`;

  if (styleElements.length > 0) {
    styleElements.forEach((styleTag, idx) => {
      const content = (styleTag.textContent || '').trim();
      if (content) {
        aggregatedCss += `/* --- Embedded Stylesheet Block #${idx + 1} --- */\n${content}\n\n`;
      }
      styleTag.remove();
    });
  } else {
    aggregatedCss += `/* Default base typography */\nbody {\n  font-family: system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;\n  line-height: 1.5;\n  margin: 0;\n  padding: 0;\n}\n`;
  }

  // 3. Extract JavaScript logic
  const scriptElements = Array.from(doc.querySelectorAll('script'));
  let aggregatedJs = `// =========================================================================
// JAVASCRIPT WORKFRAME - Extracted from ${currentUrl || 'xbrowse'}
// Page: ${pageTitle || 'Web Application'}
// Generated by xbrowse Web Framework Studio
// =========================================================================\n\n`;

  aggregatedJs += `document.addEventListener('DOMContentLoaded', function() {
  console.log('🚀 Website workframe initialized successfully');

  // Handle all form submissions with dynamic AJAX/Fetch fallback
  const forms = document.querySelectorAll('form');
  forms.forEach(function(form) {
    form.addEventListener('submit', function(e) {
      console.log('Form submission intercepted:', form.action || form.getAttribute('action') || '/submit');
    });
  });
});\n\n`;

  scriptElements.forEach((scriptTag, idx) => {
    const src = scriptTag.getAttribute('src');
    const content = (scriptTag.textContent || '').trim();

    // Skip our internal bridge
    if (scriptTag.id === '__isolated_browser_bridge__' || content.includes('BROWSER_DOM_MUTATION')) {
      scriptTag.remove();
      return;
    }

    if (content) {
      aggregatedJs += `// --- Inline Script Block #${idx + 1} ---\ntry {\n${content}\n} catch (err) {\n  console.warn('Script block #${idx + 1} notice:', err);\n}\n\n`;
      scriptTag.remove();
    } else if (src) {
      if (src.includes('/api/proxy')) {
        try {
          const u = new URL(src, window.location.origin);
          const realSrc = u.searchParams.get('url');
          if (realSrc) scriptTag.setAttribute('src', realSrc);
        } catch {}
      }
    }
  });

  // 4. Form and Structure Analysis
  const forms = Array.from(doc.querySelectorAll('form'));
  const detectedForms: PageAnalysis['detectedForms'] = [];

  forms.forEach(form => {
    const action = form.getAttribute('action') || '/submit';
    const method = (form.getAttribute('method') || 'POST').toUpperCase();
    const inputs = Array.from(form.querySelectorAll('input, select, textarea'));
    const fields = inputs
      .map(i => i.getAttribute('name') || i.getAttribute('id') || i.getAttribute('type') || 'field')
      .filter(Boolean);
    const submitBtn = form.querySelector('button[type="submit"], input[type="submit"], button');
    const buttonText = submitBtn ? (submitBtn.textContent || (submitBtn as HTMLInputElement).value || 'Submit').trim() : 'Submit';

    detectedForms.push({
      action,
      method,
      fields,
      buttonText
    });

    if (action.includes('/api/proxy')) {
      form.setAttribute('action', '/login');
    }
  });

  // 5. Clean up links and images from proxy URLs to clean absolute/relative paths
  const allAnchors = Array.from(doc.querySelectorAll('a'));
  allAnchors.forEach(a => {
    const href = a.getAttribute('href');
    if (href && href.includes('/api/proxy')) {
      try {
        const u = new URL(href, window.location.origin);
        const realUrl = u.searchParams.get('url');
        if (realUrl) a.setAttribute('href', realUrl);
      } catch {}
    }
  });

  const allImages = Array.from(doc.querySelectorAll('img'));
  allImages.forEach(img => {
    const src = img.getAttribute('src');
    if (src && src.includes('/api/proxy')) {
      try {
        const u = new URL(src, window.location.origin);
        const realUrl = u.searchParams.get('url');
        if (realUrl) img.setAttribute('src', realUrl);
      } catch {}
    }
  });

  let head = doc.head;
  if (!head) {
    head = doc.createElement('head');
    doc.documentElement.insertBefore(head, doc.body);
  }

  // Add styles.css link
  const linkCss = doc.createElement('link');
  linkCss.rel = 'stylesheet';
  linkCss.href = 'styles.css';
  head.appendChild(linkCss);

  // Add app.js script
  const scriptJs = doc.createElement('script');
  scriptJs.src = 'app.js';
  scriptJs.defer = true;
  if (doc.body) {
    doc.body.appendChild(scriptJs);
  } else {
    head.appendChild(scriptJs);
  }

  const rawCleanHtml = doc.documentElement ? '<!DOCTYPE html>\n' + doc.documentElement.outerHTML : '<!DOCTYPE html>\n<html><body></body></html>';
  const cleanFormattedHtml = formatHtml(rawCleanHtml);

  const totalNodes = doc.querySelectorAll('*').length;
  const inputCount = doc.querySelectorAll('input, select, textarea').length;
  const buttonCount = doc.querySelectorAll('button, input[type="submit"]').length;
  const imageCount = allImages.length;
  const linkCount = allAnchors.length;

  const stats: PageAnalysis = {
    url: currentUrl || 'https://example.com',
    domain,
    title: pageTitle || doc.title || 'Cloned Website',
    totalNodes,
    formCount: forms.length,
    inputCount,
    buttonCount,
    scriptCount: scriptElements.length,
    styleCount: styleElements.length,
    imageCount,
    linkCount,
    detectedForms
  };

  // 6. Generate Python Backend Workframe (Flask)
  const pythonServer = generatePythonWorkframe(stats, detectedForms);

  // 7. Generate requirements.txt
  const requirements = `flask>=3.0.0
requests>=2.31.0
urllib3>=2.0.0
gunicorn>=21.2.0
`;

  // 8. Generate Dockerfile
  const dockerfile = `# Docker container workframe for Cloned Website
FROM python:3.11-slim

WORKDIR /app

# Install system dependencies
RUN apt-get update && apt-get install -y --no-install-recommends curl && rm -rf /var/lib/apt/lists/*

# Install python packages
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

# Copy source code and workframe assets
COPY . .

# Expose server port
ENV PORT=5000
EXPOSE 5000

# Run Flask server
CMD ["python", "server.py"]
`;

  // 9. Generate detailed README.md (Hinglish + English)
  const readme = generateReadme(stats, detectedForms);

  return {
    html: cleanFormattedHtml,
    css: aggregatedCss,
    js: aggregatedJs,
    pythonServer,
    requirements,
    dockerfile,
    readme,
    stats
  };
}

function generatePythonWorkframe(stats: PageAnalysis, forms: PageAnalysis['detectedForms']): string {
  const formRoutes = forms.map((form, idx) => {
    const rawAction = form.action || `/submit_${idx + 1}`;
    const cleanRoute = rawAction.startsWith('/') ? rawAction : `/${rawAction}`;
    const routeName = cleanRoute.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^_+/, '');

    return `
@app.route('${cleanRoute}', methods=['${form.method}', 'GET'])
def handle_${routeName || 'action_' + idx}():
    """Handler for form: ${form.buttonText || cleanRoute}"""
    data = request.form.to_dict() or request.get_json(silent=True) or {}
    print(f"📥 Form Received on '${cleanRoute}': {data}")

    # Authentication simulation
    if 'user' in str(data) or 'email' in str(data) or 'login' in '${cleanRoute}'.lower():
        session['user'] = data.get('username') or data.get('user') or 'user@example.com'
        session['logged_in'] = True
        return jsonify({
            "status": "success",
            "message": "Authentication successful! Welcome to the workframe.",
            "session": session.get('user'),
            "data": data
        })

    return jsonify({
        "status": "success",
        "action": "${cleanRoute}",
        "message": "Form submission handled by Python Workframe",
        "fields_received": data
    })
`;
  }).join('\n');

  return `#!/usr/bin/env python3
# =========================================================================
# PYTHON BACKEND WORKFRAME - ${stats.title}
# Cloned Target: ${stats.url}
# Generated by xbrowse Web Framework Studio
# =========================================================================

import os
import sys
import json
from flask import Flask, render_template_string, send_from_directory, request, jsonify, session

app = Flask(__name__, static_folder='.', static_url_path='')
app.secret_key = os.environ.get('SECRET_KEY', 'xbrowse_secret_workframe_key_9f99c16d')

@app.before_request
def log_request_info():
    """Logs incoming request info in terminal"""
    print(f"🌐 [{request.method}] {request.path} from {request.remote_addr}")

@app.route('/')
def home():
    """Serves the primary cloned index.html website"""
    if os.path.exists('index.html'):
        with open('index.html', 'r', encoding='utf-8') as f:
            return f.read(), 200, {'Content-Type': 'text/html; charset=utf-8'}
    return "<h1>index.html not found</h1><p>Please place index.html in the same directory.</p>", 404

@app.route('/styles.css')
def serve_css():
    """Serves extracted CSS stylesheet"""
    return send_from_directory('.', 'styles.css', mimetype='text/css')

@app.route('/app.js')
def serve_js():
    """Serves extracted JavaScript application code"""
    return send_from_directory('.', 'app.js', mimetype='application/javascript')

# -------------------------------------------------------------------------
# DETECTED FORM HANDLERS & BACKEND API ROUTES
# -------------------------------------------------------------------------
${formRoutes || `
@app.route('/api/submit', methods=['POST', 'GET'])
def default_submit():
    data = request.form.to_dict() or request.get_json(silent=True) or {}
    return jsonify({"status": "ok", "message": "API received data", "data": data})
`}

@app.route('/api/health')
def health_check():
    """Health check endpoint"""
    return jsonify({
        "status": "healthy",
        "app": "${stats.title}",
        "cloned_from": "${stats.url}",
        "framework": "Python Flask 3.0"
    })

# Generic catch-all for static files
@app.route('/<path:filename>')
def serve_static_file(filename):
    if os.path.exists(filename):
        return send_from_directory('.', filename)
    return jsonify({"error": "File not found", "path": filename}), 404

if __name__ == '__main__':
    port = int(os.environ.get('PORT', 5000))
    host = '0.0.0.0'
    print("=" * 60)
    print("🚀 xbrowse Cloned Website - Python Backend Workframe")
    print(f"📍 Original Site: {stats.url}")
    print(f"🔗 Local URL: http://localhost:{port}")
    print("💡 To test: Open the URL above in any browser!")
    print("=" * 60)
    app.run(host=host, port=port, debug=True)
`;
}

